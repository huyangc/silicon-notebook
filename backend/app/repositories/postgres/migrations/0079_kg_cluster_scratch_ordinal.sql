-- kg_cluster_scratch gains SQLite's rowid as an explicit identity ordinal, so
-- the rebuild's write-generation step can page through one run's scratch rows
-- in insertion order. PostgreSQL only: the SQLite table already has that key
-- (its implicit rowid, which every SQLite index carries as a trailing column).
--
-- Why: write_cluster_map_generation wrote one object type's whole membership
-- with a single INSERT ... SELECT. A full recluster of a production claim type
-- is millions of rows (index maintenance on concept_clusters alone measured
-- 310-350 s at 4M rows), far over the 30 s statement timeout. The step now
-- writes keyset pages (UnifiedKgStore.write_cluster_map_generation), and a
-- keyset needs an ordered key: scratch rows had no column that orders them the
-- way the old statement wrote them. ``ordinal`` is that key. Rows are inserted
-- by Pass A2 in stream_seed_rows order (knowledge_objects.ordinal), so the
-- identity default assigns exactly the insertion order SQLite's rowid gives the
-- same rows. The table therefore joins POSTGRES_ROWID_ORDINAL_TABLES
-- (schema_manifest.py) with the same BY DEFAULT identity shape as the others.
--
-- (notebook_id, run_id, ordinal) replaces (notebook_id, run_id): every reader
-- of the old index filters on that same prefix, and keeping both would make
-- every Pass A2 insert maintain two indexes. The new index is append-ordered
-- within a run (ordinals only grow), so it adds no random page splits.
--
-- TRUNCATE first: scratch rows never outlive a process (the startup recovery
-- in maintenance.py TRUNCATEs this table right after migrations, and every
-- rebuild clears its own run in a finally). A rebuild killed outright can still
-- strand millions of rows, and this migration runs at startup under the normal
-- 30 s statement timeout; truncating makes every statement below O(1) instead
-- of a table rewrite plus an index build over whatever was stranded.
TRUNCATE kg_cluster_scratch;
ALTER TABLE kg_cluster_scratch
  ADD COLUMN ordinal bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX idx_kg_cluster_scratch_nb_run_ordinal
  ON kg_cluster_scratch (notebook_id, run_id, ordinal);
DROP INDEX idx_kg_cluster_scratch_nb_run;
