-- KG analysis findings storage. Mirrors SQLite v97 / _migration_97.
-- Design: docs/superpowers/specs/2026-10-19-kg-analysis-findings-design_zh.md
-- (sections 8.2, 8.3 and S4). Schema only: nothing writes these tables until
-- the findings rules ship, so there is no backfill.
--
-- kg_analysis_findings is the per-problem detail of the analysis ledger's
-- `findings` kind (kg_analysis_artifacts), handled exactly like
-- kg_source_profiles: one row per (notebook_id, rule_id, subject_key),
-- rewritten wholesale in the SAME transaction as its ledger row, so a reader
-- sees either the whole new list or the whole old one. subject_refs is the
-- jsonb list of source ids the subject involves (the read side derives
-- "handled" from it); evidence is the jsonb object of the numbers the rule
-- used. first_seen_kg_seq / first_seen_cluster_seq record the two generation
-- lines the problem first appeared at and are inherited across rebuilds;
-- "built at" is the ledger row's, not repeated per row. Derived data, synced
-- like the other analysis products: its change-capture function and trigger
-- are installed below (the sync manifest's since_schema = 97).
--
-- kg_analysis_marks holds USER decisions and system marks about a problem,
-- not a derived product: kind 'dismissed' (a member marked it normal) and
-- 'relink_attempted' (the kg_mutation_seq "补上关联" last finished at). A
-- rebuild never rewrites it. Environment-local, like concept_merge_candidates
-- (the other table of user decisions about a graph): not synced, no capture
-- trigger.
--
-- Both tables cascade with their notebook. Neither needs a secondary index:
-- every read is by notebook (the primary-key prefix) and a notebook holds at
-- most a few thousand findings and marks.
--
-- unified_kg_state.cluster_code_version records the code component of the
-- last merge (cluster algorithm version and the two embedding dimensions),
-- written beside cluster_input_version by the rebuild end-write and by the
-- inputs-unchanged skip path. DEFAULT '' reads as "no merge recorded under
-- this code yet", which is the truth for every existing row.
CREATE TABLE kg_analysis_findings (
  notebook_id text COLLATE "C" NOT NULL,
  rule_id text COLLATE "C" NOT NULL,
  subject_key text COLLATE "C" NOT NULL,
  subject_kind text COLLATE "C" NOT NULL,
  subject_label text COLLATE "C" NOT NULL DEFAULT '',
  subject_refs jsonb NOT NULL DEFAULT '[]'::jsonb,
  severity text COLLATE "C" NOT NULL,
  impact_objects bigint NOT NULL DEFAULT 0,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  first_seen_kg_seq bigint NOT NULL,
  first_seen_cluster_seq bigint NOT NULL,
  CONSTRAINT pk_kg_analysis_findings PRIMARY KEY (notebook_id, rule_id, subject_key)
);

CREATE TABLE kg_analysis_marks (
  notebook_id text COLLATE "C" NOT NULL,
  rule_id text COLLATE "C" NOT NULL,
  subject_key text COLLATE "C" NOT NULL,
  kind text COLLATE "C" NOT NULL,
  at_kg_seq bigint NOT NULL,
  actor_user_id text COLLATE "C" NOT NULL DEFAULT '',
  created_at timestamp with time zone NOT NULL,
  note text COLLATE "C" NOT NULL DEFAULT '',
  CONSTRAINT pk_kg_analysis_marks PRIMARY KEY (notebook_id, rule_id, subject_key, kind),
  CONSTRAINT ck_kg_analysis_marks_kind CHECK (kind IN ('dismissed', 'relink_attempted'))
);

ALTER TABLE kg_analysis_findings
  ADD CONSTRAINT fk_kg_analysis_findings_notebook_id__notebooks
  FOREIGN KEY (notebook_id) REFERENCES notebooks (id)
  ON UPDATE NO ACTION ON DELETE CASCADE;

ALTER TABLE kg_analysis_marks
  ADD CONSTRAINT fk_kg_analysis_marks_notebook_id__notebooks
  FOREIGN KEY (notebook_id) REFERENCES notebooks (id)
  ON UPDATE NO ACTION ON DELETE CASCADE;

ALTER TABLE unified_kg_state ADD COLUMN IF NOT EXISTS cluster_code_version text COLLATE "C" NOT NULL DEFAULT '';

