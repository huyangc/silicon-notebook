-- Concept mention ranking, mirrored by SQLite v109 / _migration_109.
-- Design: docs/superpowers/specs/2026-11-12-concept-mention-ranking-design_zh.md
-- section 10: independent derived table, deliberately not a new analysis
-- ledger kind. Its two generation stamps make freshness explicit without
-- changing the findings ledger contract or cluster-dependent artifact kinds.
-- Rewritten wholesale in the same publication transaction as findings.
--
-- rank=0 is the header (interfaces D1): empty canonical/representative ids
-- and zero counts, carrying the generation stamps even for an empty ranking.
-- Data rows have ranks 1..80. No secondary index is needed: notebook reads
-- follow the primary-key prefix. Notebook deletion cascades.
--
-- SYNCED, since_schema=109: capture functions and triggers are generated
-- below. A destination with different generation stamps treats it as stale.
CREATE TABLE kg_concept_ranks (
  notebook_id text COLLATE "C" NOT NULL,
  rank integer NOT NULL,
  canonical_id text COLLATE "C" NOT NULL,
  representative_object_id text COLLATE "C" NOT NULL,
  source_count integer NOT NULL,
  object_count integer NOT NULL,
  built_at_kg_seq bigint NOT NULL,
  built_at_cluster_seq bigint NOT NULL,
  CONSTRAINT pk_kg_concept_ranks PRIMARY KEY (notebook_id, rank),
  CONSTRAINT ck_kg_concept_ranks_rank CHECK (rank >= 0)
);
ALTER TABLE kg_concept_ranks
  ADD CONSTRAINT fk_kg_concept_ranks_notebook_id__notebooks
  FOREIGN KEY (notebook_id) REFERENCES notebooks (id)
  ON UPDATE NO ACTION ON DELETE CASCADE;

