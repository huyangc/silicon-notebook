"""Consumer-owned transaction contract for durable source relink work."""
from typing import Protocol


class RelinkWorkStorePort(Protocol):
    """Local maintenance receipts; never part of an archive or replicated state."""
    def enqueue(self, db: object, notebook_id: str, source_id: str, algorithm_version: int) -> None: ...
    def prepare(self, db: object, notebook_id: str, algorithm_version: int, full: bool = False) -> dict: ...
    def page(self, db: object, notebook_id: str, after_source_id: str | None, limit: int) -> list: ...
    def current_for_write(self, db: object, notebook_id: str, source_id: str, revision: int) -> bool: ...
    def finish(self, db: object, notebook_id: str, source_id: str, revision: int, before: int, after: int, edges: int) -> bool: ...
    def finish_full(self, db: object, notebook_id: str) -> bool: ...
    def summary(self, db: object, notebook_id: str) -> dict: ...
