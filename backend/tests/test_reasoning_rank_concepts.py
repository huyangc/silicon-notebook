@pytest.mark.parametrize("library_count,quotas", [(3, (7, 7, 6)), (25, (1,) * 25)])
def test_multilibrary_pages_share_quotas_across_handles_outcomes_and_ledger(repo, library_count, quotas):
    retriever, _ = _retriever(repo)
    state = _state()
    libraries = tuple(LibraryRanking(
        LibraryRankCoverage(f"nb{i}", f"库{i}", path="scope_full", scope_sources=80, exact=True),
        tuple(ConceptRankRow(f"nb{i}", f"item{j}", f"库{i}概念{j}", 80-j, 80-j, "", (), "personal")
              for j in range(80))) for i in range(library_count))
    computation = ConceptRankComputation(
        "multi", "主题", "all", libraries,
        tuple((f"nb{i}", 1, 1) for i in range(library_count)), "digest")

    def rank(_notebook_id, request, **_kwargs):
        page_number = 0
        if request.cursor:
            decoded = json.loads(base64.urlsafe_b64decode(request.cursor + "=" * (-len(request.cursor) % 4)))
            page_number = decoded["p"]
        return ConceptRankPage(computation, page_number, 20, rank_next_cursor(computation, page_number))

    retriever.concept_ranking.rank = rank
    decision = ReflectDecision(rank_concepts_query="主题")
    retriever._action_rank_concepts(state, decision)
    first_handles = dict(state.rank_handles)
    assert len(state.rankings[0].last_page_rows) == sum(quotas)
    assert "cursor=c1:p1" in retriever._rank_ledger(state)

    retriever._action_rank_concepts(state, replace(decision, rank_concepts_cursor="c1:p1"))
    rows = state.rankings[0].last_page_rows
    assert state.rankings[0].fetched_pages == (0, 1)
    assert len(rows) == state.trace[-1].detail["listed"] == sum(quotas)
    ledger = retriever._rank_ledger(state)
    for index, quota in enumerate(quotas):
        selected = [row for row in rows if row.notebook_id == f"nb{index}"]
        assert [row.canonical_id for row in selected] == [f"item{j}" for j in range(quota, 2 * quota)]
        assert f"库{index}概念{quota} —" in ledger
        assert f"库{index}概念0 —" not in ledger
    assert all(state.rank_handles[key] == value for key, value in first_handles.items())
    assert "cursor=c1:p2" in ledger

    if library_count > 20:
        retriever._action_rank_concepts(state, replace(decision, rank_concepts_cursor="c1:p79"))
        assert len(state.rankings[0].last_page_rows) == library_count
        assert all(row.canonical_id == "item79" for row in state.rankings[0].last_page_rows)
        assert "cursor=" not in retriever._rank_ledger(state)


