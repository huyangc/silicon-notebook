def _page(count=23, page_number=0, **coverage):
    rows = tuple(ConceptRankRow("nb", f"c{i}", f"概念{i}", count-i, 2*(count-i),
                               "g1" if i < 2 else "", (), "personal") for i in range(count))
    computation = ConceptRankComputation(
        "fingerprint", "主题", "all", (LibraryRanking(
            LibraryRankCoverage("nb", "测试库", path="scope_full", scope_sources=count,
                                exact=True, **coverage), rows),), (("nb", 1, 1),), "digest")
    return ConceptRankPage(computation, page_number, CONCEPT_RANK_PAGE_SIZE,
                           "next" if (page_number + 1) * CONCEPT_RANK_PAGE_SIZE < count else "")


class _Service:
    def __init__(self, error=None):
        self.calls = []
        self.computations = 0
        self.error = error

    def rank(self, notebook_id, request, **kwargs):
        self.calls.append((notebook_id, request, kwargs))
        if self.error:
            raise self.error
        memo = kwargs["memo"]
        if "fingerprint" not in memo:
            self.computations += 1
            memo["fingerprint"] = replace(_page().computation, query=request.query.strip(), scope=request.scope)
        return ConceptRankPage(memo["fingerprint"], 1 if request.cursor else 0, 20,
                               "" if request.cursor else "next")


def _retriever(repo, payload=None):
    llm = _SeqLLM([payload or {"next_action": "rank_concepts", "rank_concepts": {"query": "主题"}}])
    bind_chat_client(repo, "reasoning_agent", llm)
    retriever = ReasoningRetriever.from_repository(repo, repo.settings)
    retriever.concept_ranking = _Service()
    return retriever, llm


def _state(limits=None):
    trace = []
    return SimpleNamespace(
        enum_limits=limits or ask_retrieval_limits("exhaustive"), notebook_id="nb",
        rank_calls_used=0, rank_progress=0, rank_handles={}, rank_chains={},
        rank_memo={}, rank_log=[], rankings=[], record=trace.append, trace=trace)


@pytest.mark.parametrize("gate", ["setting", "policy", "enumeration", "seat", "zero", "spent", "no_graph"])
def test_closed_gate_removes_prompt_schema_whitelist_and_argument_parsing(repo, gate):
    retriever, llm = _retriever(repo)
    limits = ask_retrieval_limits("standard")
    kwargs = {}
    if gate == "setting":
        repo.settings.reasoning_rank_concepts_enabled = False
    elif gate == "policy":
        retriever.allow_rank_concepts = False
    elif gate == "enumeration":
        retriever.allow_enumeration = False
    elif gate == "seat":
        retriever.concept_ranking = None
    elif gate == "zero":
        limits = replace(limits, rank_calls_per_run=0)
    elif gate == "spent":
        kwargs["rank_spent"] = frozenset({"rank_concepts"})
    elif gate == "no_graph":
        kwargs["kg_actions"] = False
    decision = retriever.reflect("q", "c", limits=limits, **kwargs)
    assert decision.withheld and not decision.rank_concepts_query
    assert "rank_concepts" not in llm.reflect_prompts[0]
    assert "rank_concepts" not in llm.schema_hints[0]
    if gate != "no_graph":
        state = _state(limits)
        if gate == "spent":
            state.rank_calls_used = limits.rank_calls_per_run
        retriever._action_rank_concepts(state, ReflectDecision(next_action="rank_concepts"))
        assert state.trace[-1].detail["reason"] == "rank_concepts_unavailable"


