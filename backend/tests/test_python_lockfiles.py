"""The hash-locked Python dependency files stay in step with their ``.in`` inputs.

``backend/requirements.in`` (runtime) and ``backend/requirements-dev.in`` (test
and gate tools) declare ranges; ``scripts/lock_python_deps.sh`` compiles them
with pip-tools into ``backend/requirements.txt`` and
``backend/requirements-dev.txt``, which CI and deployment install with
``pip install --require-hashes``. This gate is offline: it never resolves
anything, it checks that the committed locks are what the lock script would
have produced from the committed inputs.
"""
from __future__ import annotations

import hashlib
import importlib.util
from pathlib import Path
import sys

from packaging.requirements import Requirement
from packaging.version import Version
import pytest


ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"
RUNTIME_IN = BACKEND / "requirements.in"
RUNTIME_LOCK = BACKEND / "requirements.txt"
DEV_IN = BACKEND / "requirements-dev.in"
DEV_LOCK = BACKEND / "requirements-dev.txt"
PAIRS = ((RUNTIME_IN, RUNTIME_LOCK), (DEV_IN, DEV_LOCK))
TEST_ONLY_PACKAGES = ("pytest", "pytest-xdist")

_spec = importlib.util.spec_from_file_location(
    "python_lockfiles", ROOT / "scripts" / "python_lockfiles.py"
)
assert _spec is not None and _spec.loader is not None
lockfiles = importlib.util.module_from_spec(_spec)
# dataclasses resolves its string annotations through sys.modules.
sys.modules.setdefault(_spec.name, lockfiles)
_spec.loader.exec_module(lockfiles)


def _parse_lock(path: Path):
    return lockfiles.parse_lock(path)


def _direct_requirements(path: Path) -> dict[str, Requirement]:
    direct: dict[str, Requirement] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.partition(" #")[0].strip()
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        requirement = Requirement(line)
        direct[lockfiles.canonical_name(requirement.name)] = requirement
    return direct


@pytest.mark.parametrize(("source", "lock"), PAIRS, ids=lambda path: path.name)
def test_each_lock_was_compiled_from_its_current_input(source, lock) -> None:
    """Editing a ``.in`` file without rerunning the lock script fails here."""
    recorded = lockfiles.recorded_fingerprint(lock)
    assert recorded is not None, (
        f"{lock.name} carries no input fingerprint; run: bash scripts/lock_python_deps.sh"
    )
    assert recorded == lockfiles.input_fingerprint(source), (
        f"{lock.name} is stale against {source.name}; run: bash scripts/lock_python_deps.sh"
    )


@pytest.mark.parametrize(("source", "lock"), PAIRS, ids=lambda path: path.name)
def test_each_lock_is_a_python_313_pip_compile_output_of_the_lock_script(
    source, lock,
) -> None:
    header = lock.read_text(encoding="utf-8").splitlines()[:8]
    assert "# This file is autogenerated by pip-compile with Python 3.13" in header
    assert "#    bash scripts/lock_python_deps.sh" in header


@pytest.mark.parametrize(("source", "lock"), PAIRS, ids=lambda path: path.name)
def test_every_direct_requirement_is_pinned_inside_its_declared_range(
    source, lock,
) -> None:
    entries = _parse_lock(lock)
    origin = f"-r {source.name}"
    for name, requirement in _direct_requirements(source).items():
        assert name in entries, f"{name} from {source.name} is not in {lock.name}"
        entry = entries[name]
        assert requirement.specifier.contains(
            Version(entry.version), prereleases=True
        ), f"{lock.name}: {name}=={entry.version} is outside {requirement.specifier}"
        assert origin in entry.via, f"{lock.name}: {name} is not marked {origin!r}"


@pytest.mark.parametrize(("source", "lock"), PAIRS, ids=lambda path: path.name)
def test_every_locked_package_is_still_required(source, lock) -> None:
    """A removed direct requirement or a stale transitive pin fails here."""
    entries = _parse_lock(lock)
    direct = _direct_requirements(source)
    origin = f"-r {source.name}"
    for name, entry in entries.items():
        assert entry.via, f"{lock.name}: {name} says nothing requires it"
        for reason in entry.via:
            if reason == origin:
                assert name in direct, f"{lock.name}: {name} is no longer in {source.name}"
            elif reason.startswith("-c "):
                assert reason == "-c requirements.txt" and lock == DEV_LOCK, reason
            else:
                parent = lockfiles.canonical_name(reason.split()[0])
                assert parent in entries, (
                    f"{lock.name}: {name} is required by {reason!r}, which is not locked"
                )


def test_the_dev_lock_installs_on_top_of_the_runtime_lock() -> None:
    """Shared packages keep the runtime lock's exact version and hashes, so
    ``pip install --require-hashes -r requirements.txt -r requirements-dev.txt``
    never sees two different pins for one package."""
    assert "-c requirements.txt" in lockfiles.input_lines(DEV_IN)
    runtime = _parse_lock(RUNTIME_LOCK)
    dev = _parse_lock(DEV_LOCK)
    shared = sorted(set(runtime) & set(dev))
    assert shared, "the dev lock shares no package with the runtime lock"
    for name in shared:
        assert (dev[name].version, dev[name].hashes) == (
            runtime[name].version, runtime[name].hashes,
        ), name
        assert "-c requirements.txt" in dev[name].via, name


def test_test_tools_stay_out_of_the_runtime_lock() -> None:
    runtime = _parse_lock(RUNTIME_LOCK)
    dev = _parse_lock(DEV_LOCK)
    for name in TEST_ONLY_PACKAGES:
        assert name not in runtime, name
        assert name in dev, name
    assert set(_direct_requirements(DEV_IN)).isdisjoint(_direct_requirements(RUNTIME_IN))


def test_the_fingerprint_ignores_formatting_but_not_resolution_inputs(tmp_path) -> None:
    base = tmp_path / "base.in"
    base.write_text("-c requirements.txt\nfoo[b,a]>=1,<2  # why\nBar_Baz\n", encoding="utf-8")
    same = tmp_path / "same.in"
    same.write_text(
        "# header\n\nbar-baz\nFOO[a, b] < 2 , >= 1\n-c  requirements.txt\n",
        encoding="utf-8",
    )
    assert lockfiles.input_fingerprint(same) == lockfiles.input_fingerprint(base)
    for changed in (
        "-c requirements.txt\nfoo[a]>=1,<2\nbar-baz\n",
        "-c requirements.txt\nfoo[a,b]>=1,<3\nbar-baz\n",
        "-c requirements.txt\nfoo[a,b]>=1,<2\nbar-baz; sys_platform == 'linux'\n",
        "foo[a,b]>=1,<2\nbar-baz\n",
        "-c requirements.txt\nfoo[a,b]>=1,<2\n",
    ):
        other = tmp_path / "other.in"
        other.write_text(changed, encoding="utf-8")
        assert lockfiles.input_fingerprint(other) != lockfiles.input_fingerprint(base), changed


def test_stamping_replaces_the_previous_fingerprint(tmp_path) -> None:
    source = tmp_path / "requirements.in"
    source.write_text("foo>=1\n", encoding="utf-8")
    lock = tmp_path / "requirements.txt"
    lock.write_text(f"foo==1.0 \\\n    --hash=sha256:{'0' * 64}\n{lockfiles.STAMP_PREFIX}old\n\n", encoding="utf-8")
    lockfiles.stamp(source, lock)
    lockfiles.stamp(source, lock)
    text = lock.read_text(encoding="utf-8")
    assert text.count(lockfiles.STAMP_PREFIX) == 1
    assert lockfiles.recorded_fingerprint(lock) == lockfiles.input_fingerprint(source)
    assert text.endswith(lockfiles.stamp_line(source) + "\n")


def test_the_lock_parser_rejects_what_the_lock_script_never_writes(tmp_path) -> None:
    digest = "0" * 64
    for text in (
        "foo>=1.0 \\\n    --hash=sha256:" + digest + "\n",
        "foo==1.0\n",
        "--index-url https://example.invalid/simple\nfoo==1.0 \\\n    --hash=sha256:" + digest + "\n",
        "foo==1.0 \\\n    --hash=md5:abc\n",
        "foo==1.0 \\\n    --hash=sha256:" + digest + "\nFoo==1.0 \\\n    --hash=sha256:" + digest + "\n",
    ):
        lock = tmp_path / "requirements.txt"
        lock.write_text(text, encoding="utf-8")
        with pytest.raises(ValueError):
            lockfiles.parse_lock(lock)


def test_the_wheelhouse_lock_pins_each_package_to_its_one_wheel(tmp_path) -> None:
    wheelhouse = tmp_path / "wheelhouse"
    wheelhouse.mkdir()
    published = wheelhouse / "foo_bar-1.0-py3-none-any.whl"
    published.write_bytes(b"published by the index")
    built = wheelhouse / "hnswlib-0.8.0-cp313-cp313-linux_x86_64.whl"
    built.write_bytes(b"built on the packaging host")
    (wheelhouse / "pip-26.2-py3-none-any.whl").write_bytes(b"bootstrap only")
    published_hash = hashlib.sha256(b"published by the index").hexdigest()
    built_hash = hashlib.sha256(b"built on the packaging host").hexdigest()
    sdist_hash = "1" * 64
    lock = tmp_path / "requirements.txt"
    lock.write_text(
        f"foo-bar==1.0 \\\n    --hash=sha256:{'2' * 64} \\\n    --hash=sha256:{published_hash}\n"
        "    # via -r requirements.in\n"
        f"hnswlib==0.8.0 \\\n    --hash=sha256:{sdist_hash}\n    # via -r requirements.in\n",
        encoding="utf-8",
    )

    text, built_names = lockfiles.wheelhouse_lock(lock, wheelhouse)

    out = tmp_path / "locked-wheels.txt"
    out.write_text(text, encoding="utf-8")
    entries = lockfiles.parse_lock(out)
    assert {name: (entry.version, entry.hashes) for name, entry in entries.items()} == {
        "foo-bar": ("1.0", {published_hash}),
        "hnswlib": ("0.8.0", {built_hash}),
    }
    assert built_names == [built.name]

    built.unlink()
    with pytest.raises(ValueError, match="hnswlib==0.8.0"):
        lockfiles.wheelhouse_lock(lock, wheelhouse)
