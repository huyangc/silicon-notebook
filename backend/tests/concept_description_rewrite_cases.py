def _published(repo, notebook_id):
    with repo._runtime.database.connect() as db:
        rows = repo._runtime.knowledge_lifecycle.unified_kg.cluster_description_rows(
            db, notebook_id)
    return {str(r["canonical_id"]): (r["canonical_description"], r["canonical_desc_sig"])
            for r in rows}
