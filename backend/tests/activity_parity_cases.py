"""``list_user_activity`` 的时间边界输入用例表——**两个后端共用同一张表**。

沿用 ``test_query_syntax.py`` 的 ``PARITY_CASES`` 惯例:同一组输入喂 SQLite 与
PostgreSQL 两份实现,断言行集逐位一致。

这张表存在的理由是一次真实的分叉:``"2026-07-31T16:00:00.000Z"``(UTC+8 主机上
``new Date("2026-08-01").toISOString()`` 的原样输出)曾让 SQLite 多返回 8 小时的
行、PostgreSQL 一行不返回;而两份测试恰好各喂各的输入形态(SQLite 用裸 naive、
PostgreSQL 用 ``+00:00``),这条分叉一个断言都不会红。用例表把「同一时刻的不同写
法必须选出同一批行」变成两侧都跑的硬断言。

不是测试模块(文件名不以 ``test_`` 开头),pytest 不收集它;两份测试 import 它。
"""
from __future__ import annotations


# 五行 ask,时刻按 UTC 明确写死。SQLite 侧原样当 created_at 文本写入,PostgreSQL 侧
# 解析成 aware datetime 写入——同一批绝对时刻,两边的存储形态各按各的原生类型。
ACTIVITY_ROWS = (
    ("ask-a", "2026-07-31T15:59:59+00:00"),
    ("ask-b", "2026-07-31T16:00:00+00:00"),
    ("ask-c", "2026-07-31T20:00:00+00:00"),
    ("ask-d", "2026-08-01T16:00:00+00:00"),
    ("ask-e", "2026-08-01T16:00:01+00:00"),
)

# 同一个绝对时刻 2026-07-31T16:00:00Z 的五种合法写法。最后一条是裸 naive:按
# app.core.activity_time 的契约按 UTC 读(不是本机时区),所以它与前四条等价。
_SAME_INSTANT = (
    "2026-07-31T16:00:00.000Z",
    "2026-07-31T16:00:00Z",
    "2026-07-31T16:00:00+00:00",
    "2026-08-01T00:00:00+08:00",
    "2026-07-31T16:00:00",
)

# (since, until, 期望的 id 集合)。since 是闭端、until 是开端(半开区间)。
BOUND_PARITY_CASES = (
    *(
        (spelling, None, {"ask-b", "ask-c", "ask-d", "ask-e"})
        for spelling in _SAME_INSTANT
    ),
    *((None, spelling, {"ask-a"}) for spelling in _SAME_INSTANT),
    ("2026-07-31T16:00:00.000Z", "2026-08-01T16:00:00.000Z", {"ask-b", "ask-c"}),
    ("2026-08-01T00:00:00+08:00", "2026-08-02T00:00:00+08:00", {"ask-b", "ask-c"}),
    ("2026-07-31T16:00:00", "2026-08-01T16:00:00", {"ask-b", "ask-c"}),
    # 窗口整个落在数据之外 / 之前,两侧都必须是空集(不是「忽略这个边界」)。
    ("2026-09-01T00:00:00+00:00", None, set()),
    (None, "2026-07-01T00:00:00+00:00", set()),
)

# ----------------------------------------------------- 「浏览器本地日」窗口(F1)
#
# 上面的 BOUND_PARITY_CASES 全部是**同一个绝对时刻的不同写法**,它证明的是「写法不
# 影响行集」,证明不了**日边界**落在哪里。这一组补的正是那件事。
#
# 场景:浏览器在 UTC+8,用户在日期选择器里点「8月4日」。前端 dayRange() 产出的边界
# 就是下面这两个带偏移的串(见 frontend/app/dev/logs/date.ts)。
#
# 这组用例钉住的回归:边界曾经是**裸串** `2026-08-04T00:00:00`,而
# app.core.activity_time 的契约把裸串**按 UTC 读** —— 于是 `2026-08-04T06:30:00+08:00`
# 的那一行(当地 8月4日早上)落在窗口外,选「8月4日」看不到它、选「8月3日」才出现,
# 而那一行自己显示的时间(按浏览器本地渲染)写的就是 8月4日 06:30。同一屏自相矛盾。
#
# 把 LOCAL_DAY_SINCE/UNTIL 改回裸串(去掉 `+08:00`)即可让这组用例报红:窗口会整个
# 平移 8 小时,选出 {day-late, day-next-open} 而不是期望的三行。
LOCAL_DAY_SINCE = "2026-08-04T00:00:00+08:00"
LOCAL_DAY_UNTIL = "2026-08-05T00:00:00+08:00"

# 五行 ask,全部带 +08:00(与 repository_facade._now() 现在写出的形态一致)。刻意
# 覆盖窗口两端:当地 00:00 是闭端(在窗口内)、次日当地 00:00 是开端(在窗口外)。
LOCAL_DAY_ROWS = (
    ("day-prev-late", "2026-08-03T23:59:59+08:00"),   # 前一天当地 23:59:59 → 窗口外
    ("day-open", "2026-08-04T00:00:00+08:00"),        # 当地 00:00 → 窗口内(闭端)
    ("day-early", "2026-08-04T06:30:00+08:00"),       # 实测触发点(整改前看不到)
    ("day-late", "2026-08-04T23:59:59+08:00"),        # 当地 23:59:59 → 窗口内
    ("day-next-open", "2026-08-05T00:00:00+08:00"),   # 次日当地 00:00 → 窗口外(开端)
)

LOCAL_DAY_EXPECTED = {"day-open", "day-early", "day-late"}


# 畸形边界:两个后端必须抛同一种异常(ValueError),不许一个静默返回一页、另一个 500。
MALFORMED_BOUNDS = (
    "not-a-date",
    "",
    "2026-08-01T99:99:99+00:00",
    "2026/08/01",
    "yesterday",
)
