#!/usr/bin/env python3
"""Regenerate (or, with --check, verify) the generated half of every packaged
PostgreSQL migration that installs source-side change capture
(`app.migration.sync.capture_contract.CAPTURE_MIGRATION_FILES`: 0064 for the
46 tables synced when capture landed, and one later migration per table made
SYNCED afterwards) from `app.migration.sync.capture`.

0064 carries one plpgsql trigger function and one row trigger per table synced
at SQLite v84 (46 of each); a later capture migration carries the pair for
exactly the tables whose `TableSyncSpec.since_schema` names it. Each file is
rendered for ITS OWN version (`added_at=<version>`), never for the current
manifest, so adding a synced table never re-renders an applied migration.
They are not hand-written: the same
generator renders the SQLite triggers `_migration_84` installs, the
expectations `scripts/verify_repository_snapshot.py` holds a migrated database
to, and this file. `app.migration.shadow.postgres_catalog` then parses the
function bodies and trigger statements straight back out of this file and
holds the live PostgreSQL catalog to them, so an edit here is a schema change,
not a comment fix.

Only the text BELOW the generated marker is rendered. Everything above it --
the header, the two control tables, the de-duplication and the two composite
primary keys -- is hand-written and this script preserves it byte for byte, so
re-rendering after a manifest change never silently rewrites the hand-written
half.

Usage:
    python3 scripts/generate_sync_capture_migration.py          # rewrite stale files
    python3 scripts/generate_sync_capture_migration.py --check  # verify only, no write

--check exits non-zero and names the first differing line when the committed
migration is stale (e.g. a table was added to the sync manifest but the
migration was not re-rendered). It is wired into scripts/check_contracts.sh,
the same way `generate_ui_extension_contract.py --check` is, so a stale
migration fails the contracts lane rather than waiting for the backend lane's
`backend/tests/test_sync_capture.py`.

Re-rendering an ALREADY APPLIED migration is not a normal operation: a
deployed database has the old text's checksum in `silicon_schema_migrations`
and would refuse to start (see `PostgresMigrator._validate_ledger`). This
script exists for the window in which a capture migration is still unreleased,
and for reviewers who want to prove the committed text is what the generator
produces; `--check` on an applied migration must keep passing unchanged.
"""
from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app.migration.sync.capture import (  # noqa: E402
    postgres_function_sql,
    postgres_trigger_sql,
)
from app.migration.sync.capture_contract import CAPTURE_MIGRATION_FILES  # noqa: E402


MIGRATIONS_DIR = ROOT / "backend" / "app" / "repositories" / "postgres" / "migrations"
# The hand-written half ends here; this exact line must appear once.
GENERATED_MARKER = (
    "-- --- generated by backend/app/migration/sync/capture.py "
    "---------------------\n"
)


def render_generated_half(schema: int) -> str:
    """Every function immediately followed by its own trigger, in the sync
    manifest's copy order, blank-line separated -- for the tables the
    migration of SQLite schema ``schema`` installs."""
    triggers = postgres_trigger_sql(added_at=schema)
    blocks: list[str] = []
    for _name, (table, function_sql) in postgres_function_sql(added_at=schema).items():
        trigger_sql = triggers[f"sync_capture_{table}"][1]
        blocks.append(f"{function_sql};\n{trigger_sql};\n")
    return "\n".join(blocks)


def render_migration(path: Path, schema: int, committed: str) -> str:
    """The full file: the committed hand-written prefix plus a fresh
    generated half."""
    parts = committed.split(GENERATED_MARKER)
    if len(parts) != 2:
        raise SystemExit(
            f"{path}: expected exactly one generated marker, "
            f"found {len(parts) - 1}"
        )
    return parts[0] + GENERATED_MARKER + render_generated_half(schema)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed migration matches the generator; do not write",
    )
    arguments = parser.parse_args()

    status = 0
    for schema, file_name in sorted(CAPTURE_MIGRATION_FILES.items()):
        path = MIGRATIONS_DIR / file_name
        committed = path.read_text(encoding="utf-8")
        rendered = render_migration(path, schema, committed)
        if committed == rendered:
            if not arguments.check:
                print(f"sync capture migration: unchanged ({path.name})")
            continue
        if arguments.check:
            diff = list(
                difflib.unified_diff(
                    committed.splitlines(keepends=True),
                    rendered.splitlines(keepends=True),
                    fromfile="committed",
                    tofile="generated",
                    n=1,
                )
            )
            sys.stderr.write(
                f"{path.name} is stale; re-run "
                "`python3 scripts/generate_sync_capture_migration.py`\n"
            )
            sys.stderr.writelines(diff[:40])
            status = 1
            continue
        path.write_text(rendered, encoding="utf-8")
        print(f"sync capture migration: rewritten ({path.name})")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
