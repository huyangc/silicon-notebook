test("a second sync is idempotent, and dropping the variable removes the stale copies", async (t) => {
  const { root, frontendDir } = await makeWorkspace(t);
  const alpha = await writePackage(root, "alpha", {
    manifest: manifestFor("alpha", { component: "AlphaEntry" }),
  });

  await syncUiPlugins({ frontendDir, roots: [alpha] });
  const firstRegistry = await readFile(registryPath(frontendDir), "utf8");
  const firstListing = (await readdir(path.join(frontendDir, "features", "ext-alpha"))).sort();

  await syncUiPlugins({ frontendDir, roots: [alpha] });
  assert.equal(await readFile(registryPath(frontendDir), "utf8"), firstRegistry);
  assert.deepEqual(
    (await readdir(path.join(frontendDir, "features", "ext-alpha"))).sort(),
    firstListing,
  );

  await syncUiPlugins({ frontendDir, roots: [] });
  assert.deepEqual(
    (await readdir(path.join(frontendDir, "features"))).sort(),
    ["extension-sdk"],
  );
  assert.equal(await readFile(registryPath(frontendDir), "utf8"), EMPTY_REGISTRY);
});


test("a hand-written features/ext-* directory without the marker is refused, not deleted", async (t) => {
  const { root, frontendDir } = await makeWorkspace(t);
  const alpha = await writePackage(root, "alpha", {
    manifest: manifestFor("alpha", { component: "AlphaEntry" }),
  });
  await syncUiPlugins({ frontendDir, roots: [alpha] });
  const registryBefore = await readFile(registryPath(frontendDir), "utf8");

  // `ext-zzz-…` 排在 `ext-alpha` 之后：勘察若与删除交错，抛错时 alpha 已经没了，
  // 而 registry.local.ts 还指着它——之后每次 build 都红且不自愈。
  const handWritten = path.join(frontendDir, "features", "ext-zzz-handwritten");
  await mkdir(handWritten, { recursive: true });
  await writeFile(
    path.join(handWritten, "workspace-plugin.ts"),
    "export const Entry = () => null;\n",
    "utf8",
  );

  await assert.rejects(
    syncUiPlugins({ frontendDir, roots: [alpha] }),
    /carries no \.ui-plugin-origin marker/,
  );
  assert.deepEqual(await readdir(handWritten), ["workspace-plugin.ts"]);
  assert.equal(existsSync(path.join(frontendDir, "features", "ext-alpha")), true);
  assert.equal(await readFile(registryPath(frontendDir), "utf8"), registryBefore);
});


test("a features/ext-* symlink is refused instead of being written through", async (t) => {
  const { root, frontendDir } = await makeWorkspace(t);
  const sdkDir = path.join(frontendDir, "features", "extension-sdk");
  const victim = path.join(sdkDir, "contracts.ts");
  const original = "export type WorkspaceUiContribution = never;\n";
  await writeFile(victim, original, "utf8");
  // 包里带一个与 SDK 同名的文件：`ext-alpha` 是软链时，跳过删除再 mkdir+copyFile
  // 会顺着它把受版本控制的 SDK 源码整个覆盖掉。
  const alpha = await writePackage(root, "alpha", {
    manifest: manifestFor("alpha", { component: "AlphaEntry" }),
    extras: { "contracts.ts": "export const HIJACKED = true;\n" },
  });
  await symlink(sdkDir, path.join(frontendDir, "features", "ext-alpha"), "dir");

  await assert.rejects(
    syncUiPlugins({ frontendDir, roots: [alpha] }),
    /is not a real directory/,
  );
  assert.equal(await readFile(victim, "utf8"), original);
  assert.equal(existsSync(path.join(sdkDir, "ui-plugin.json")), false);
  assert.equal(existsSync(path.join(sdkDir, ".ui-plugin-origin")), false);
  assert.equal(existsSync(registryPath(frontendDir)), false);
});


test("a rejected sync leaves the previous copies, registry and contract byte-for-byte intact", async (t) => {
  const { root, frontendDir } = await makeWorkspace(t);
  const alpha = await writePackage(root, "alpha", {
    manifest: manifestFor("alpha", { component: "AlphaEntry" }),
  });
  const copiedEntry = path.join(frontendDir, "features", "ext-alpha", "workspace-plugin.tsx");

  await syncUiPlugins({ frontendDir, roots: [alpha] });
  const registryBefore = await readFile(registryPath(frontendDir), "utf8");
  const contractBefore = await readFile(contractPath(frontendDir), "utf8");
  const copyBefore = await readFile(copiedEntry, "utf8");

  // ① 一个不合法的输入包：全部校验都在删除之前跑完，A 的副本一个字节都不能变。
  const broken = await writePackage(root, "broken", { extras: { "styles.css": ".x {}\n" } });
  await assert.rejects(
    syncUiPlugins({ frontendDir, roots: [alpha, broken] }),
    /"styles\.css" is not an allowed package file/,
  );
  assert.equal(await readFile(registryPath(frontendDir), "utf8"), registryBefore);
  assert.equal(await readFile(copiedEntry, "utf8"), copyBefore);

  // ② 内建契约 fixture 读不到也必须在勘察阶段就发现：把它留到最后一步会先删掉旧
  //    副本、写完空 registry，再抛错，留下一棵和契约文件互相矛盾的树。
  await rm(path.join(root, "backend", "tests", "fixtures", "ui_extension_contract.json"));
  await assert.rejects(
    syncUiPlugins({ frontendDir, roots: [] }),
    /built-in UI extension contract fixture is missing/,
  );
  assert.equal(await readFile(registryPath(frontendDir), "utf8"), registryBefore);
  assert.equal(await readFile(contractPath(frontendDir), "utf8"), contractBefore);
  assert.equal(await readFile(copiedEntry, "utf8"), copyBefore);
});


test("two packages exporting the same component name get distinct import bindings", async (t) => {
  const { root, frontendDir } = await makeWorkspace(t);
  // 两个包的 manifest 都指名 `SearchEntry`：裸名字会让生成文件出现两条同名 import，
  // `tsc` 报重复标识符、整个前端构建挂在一份「do not edit」的文件上。
  const alpha = await writePackage(root, "alpha");
  const beta = await writePackage(root, "beta");

  await syncUiPlugins({ frontendDir, roots: [alpha, beta] });

  const rendered = await readFile(registryPath(frontendDir), "utf8");
  const imported = [...rendered.matchAll(/^import \{ (.+) \} from "\.\.\/ext-/gm)]
    .map((hit) => hit[1]);
  assert.deepEqual(imported, [
    "SearchEntry as ext_alpha__SearchEntry",
    "SearchEntry as ext_beta__SearchEntry",
  ]);
  assert.ok(rendered.includes("    Component: ext_alpha__SearchEntry,"));
  assert.ok(rendered.includes("    Component: ext_beta__SearchEntry,"));
  const bound = imported.map((clause) => clause.split(" as ").at(-1));
  assert.equal(new Set(bound).size, bound.length, "every binding must be declared once");
});


test("dotfiles in the package root are skipped, while subdirectories stay refused", async (t) => {
  const { root, frontendDir } = await makeWorkspace(t);
  const directory = await writePackage(root, "alpha", {
    manifest: manifestFor("alpha", { component: "AlphaEntry" }),
    extras: { ".DS_Store": "junk\n", ".gitignore": "node_modules\n" },
  });

  const inspected = await inspectPackage(directory);
  assert.deepEqual(inspected.skipped, [".DS_Store", ".gitignore"]);
  assert.deepEqual(inspected.files, ["ui-plugin.json", "workspace-plugin.tsx"]);

  await syncUiPlugins({ frontendDir, roots: [directory] });
  assert.deepEqual(
    (await readdir(path.join(frontendDir, "features", "ext-alpha"))).sort(),
    [".ui-plugin-origin", "ui-plugin.json", "workspace-plugin.tsx"],
  );

  // 子目录仍一律拒绝，`.git` 也不例外——它会被 next build 的类型检查连同 worktree
  // 里的一切一起吞进去，和 `node_modules/` 同类。
  const dotted = await writePackage(root, "dotted", { directories: [".git"] });
  await assert.rejects(
    syncUiPlugins({ frontendDir, roots: [dotted] }),
    /subdirectory "\.git" is not allowed/,
  );
});


test("the contract sort key is the one the backend generator uses", async () => {
  const generatorModule = await readFile(
    path.join(REPO_DIR, "scripts", "generate_ui_extension_contract.py"),
    "utf8",
  );
  const declared = generatorModule.match(/_CONTRIBUTION_SORT_FIELDS = \(([^)]*)\)/);
  assert.ok(declared, "backend generator must declare _CONTRIBUTION_SORT_FIELDS");
  const backendFields = [...declared[1].matchAll(/"([a-z_]+)"/g)].map((hit) => hit[1]);
  assert.deepEqual(
    backendFields,
    ["plugin_id", "version", "contribution_id", "slot", "capability"],
  );

  // 每个字段单独造一次并列，证明比较确实按声明顺序逐级下推。
  function rowWith(overrides) {
    return {
      plugin_id: "m",
      version: "m",
      contribution_id: "m",
      slot: "m",
      capability: "m",
      ...overrides,
    };
  }
  for (const field of backendFields) {
    const low = rowWith({ [field]: "a" });
    const high = rowWith({ [field]: "z" });
    assert.deepEqual(mergeContractRows([high], [low]), [low, high], field);
  }
  const earlier = rowWith({ plugin_id: "a", capability: "z" });
  const later = rowWith({ plugin_id: "z", capability: "a" });
  assert.deepEqual(mergeContractRows([later], [earlier]), [earlier, later]);
});
