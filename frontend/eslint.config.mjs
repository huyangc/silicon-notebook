// ESLint gate for the frontend (`npm run lint`, run by scripts/check_frontend.sh).
//
// Rule set: Next's own `next/core-web-vitals` + `next/typescript` (which bring
// eslint-plugin-react-hooks), loaded through FlatCompat because
// eslint-config-next 15 still ships eslintrc-format configs.
//
// Every rule is an error. Pre-existing violations live in
// eslint-suppressions.json (ESLint's bulk suppressions, counted per file and
// rule), and suppressions only ever record errors: a warning could neither be
// baselined nor fail the gate, so a "warn" rule would be no rule at all.
// What enforces the baseline, and what review still has to catch, is in
// docs/development.md, "Frontend ESLint gate".
import path from "node:path";
import { fileURLToPath } from "node:url";

import { FlatCompat } from "@eslint/eslintrc";

const compat = new FlatCompat({
  baseDirectory: path.dirname(fileURLToPath(import.meta.url)),
});

/** Same config with every enabled rule raised from "warn" to "error". */
function asErrors(config) {
  if (!config.rules) return config;
  const rules = {};
  for (const [name, value] of Object.entries(config.rules)) {
    const [level, ...options] = Array.isArray(value) ? value : [value];
    const isWarn = level === "warn" || level === 1;
    rules[name] = isWarn ? ["error", ...options] : value;
  }
  return { ...config, rules };
}

const config = [
  {
    // ESLint does not read .gitignore (and @eslint/compat's includeIgnoreFile
    // is not a dependency), so the generated and output directories the root
    // .gitignore lists are named here. tests/guards/eslint-baseline-guard pins
    // this list.
    ignores: [
      ".next/**",
      "node_modules/**",
      "next-env.d.ts",
      ".local/**",
      "coverage/**",
      "dist/**",
      "build/**",
      // Generated by scripts/sync-ui-plugins.mjs from out-of-tree plugin
      // packages (gitignored); their authors own their lint.
      "features/ext-*/**",
      "features/extension-sdk/registry.local.ts",
    ],
  },
  {
    // A disable comment that no longer suppresses anything is itself a failure
    // (it has no rule id, so it can never be baselined): delete it.
    linterOptions: { reportUnusedDisableDirectives: "error" },
  },
  ...compat.extends("next/core-web-vitals", "next/typescript").map(asErrors),
  {
    rules: {
      "react-hooks/rules-of-hooks": "error",
      "react-hooks/exhaustive-deps": "error",
      // A leading underscore is this codebase's spelling of "deliberately
      // unused" (positional callback parameters, destructured-away fields).
      "@typescript-eslint/no-unused-vars": [
        "error",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
          destructuredArrayIgnorePattern: "^_",
          ignoreRestSiblings: true,
        },
      ],
    },
  },
  {
    // These two Next rules guard what Next bundles and serves: `<img>` costs
    // page LCP, and a binding named `module` breaks webpack's module wrapper.
    // Tests are never served or bundled by Next (node --test / Vitest).
    files: ["tests/**"],
    rules: {
      "@next/next/no-img-element": "off",
      "@next/next/no-assign-module-variable": "off",
    },
  },
];

export default config;
